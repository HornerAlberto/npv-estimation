"""Monthly value model for the internal R&D project.

See docs/business-context.md for the methodology and docs/scenarios.md for the
benefit scenarios.

For each month t = 1 ... horizon:

    net_flow(t) = benefit(t) - direct_costs(t) - opportunity_cost

    opportunity_cost = n_rd_consultants * billing_rate * occupation * dedication
    benefit(t)       = billing_rate * benefit_margin * consultants staffed in month t

Flows are discounted monthly with npv.py (CF_0 = 0, annual rate converted with
effective compounding).
"""

from dataclasses import dataclass, replace

import pandas as pd

from npv import npv_table

OPPORTUNITY_COST = "Consultant time (opportunity cost)"

# Types for direct monthly costs (everything except consultants' time).
COST_TYPES = [
    "Licences",
    "Cloud computing",
    "Tools & equipment",
    "Training",
    "External services",
    "Other",
]


@dataclass(frozen=True)
class Opportunity:
    """Client work generated by the R&D: from start_month on, `consultants` bill full time."""

    start_month: int
    consultants: float


@dataclass(frozen=True)
class Scenario:
    name: str
    horizon_months: int
    opportunities: tuple[Opportunity, ...]


@dataclass(frozen=True)
class CostItem:
    """A direct monthly cost, active from start_month to end_month (None = whole horizon)."""

    name: str
    cost_type: str
    monthly_amount: float
    start_month: int = 1
    end_month: int | None = None

    def amount_in(self, month: int) -> float:
        active = self.start_month <= month and (
            self.end_month is None or month <= self.end_month
        )
        return self.monthly_amount if active else 0.0


@dataclass(frozen=True)
class Params:
    n_rd_consultants: float = 3
    billing_rate_monthly: float = 12_000
    occupation: float = 0.73
    dedication: float = 1.0
    benefit_margin: float = 1.0
    annual_rate: float = 0.12


DEFAULT_SCENARIOS: tuple[Scenario, ...] = (
    Scenario("1. One opportunity", 12, (Opportunity(5, 4),)),
    Scenario("2. Two opportunities", 12, (Opportunity(4, 3), Opportunity(6, 7))),
    Scenario(
        "3. Scenario 1 over 3 years",
        36,
        (Opportunity(5, 4), Opportunity(13, 5), Opportunity(25, 4)),
    ),
    Scenario(
        "4. Scenario 2 over 3 years",
        36,
        (Opportunity(4, 3), Opportunity(6, 7), Opportunity(13, 9), Opportunity(25, 5)),
    ),
)

DEFAULT_COSTS: tuple[CostItem, ...] = (
    CostItem("Cloud compute", "Cloud computing", 1_500),
    CostItem("Software licences", "Licences", 800),
)


def opportunity_cost(params: Params) -> float:
    """Monthly billing forgone because consultants work on R&D."""
    return (
        params.n_rd_consultants
        * params.billing_rate_monthly
        * params.occupation
        * params.dedication
    )


def consultants_staffed(scenario: Scenario, month: int) -> float:
    """Consultants billing on R&D-generated work in a month (additive, persistent)."""
    return sum(o.consultants for o in scenario.opportunities if o.start_month <= month)


def monthly_flows(
    scenario: Scenario, params: Params, costs: tuple[CostItem, ...] = DEFAULT_COSTS
) -> pd.DataFrame:
    """One row per month with benefit, costs, net flow and discounting."""
    opp_cost = opportunity_cost(params)
    rows = []
    for month in range(1, scenario.horizon_months + 1):
        staffed = consultants_staffed(scenario, month)
        benefit = staffed * params.billing_rate_monthly * params.benefit_margin
        direct = sum(c.amount_in(month) for c in costs)
        rows.append(
            {
                "month": month,
                "consultants_staffed": staffed,
                "benefit": benefit,
                "opportunity_cost": opp_cost,
                "direct_costs": direct,
                "total_cost": opp_cost + direct,
                "net_flow": benefit - opp_cost - direct,
            }
        )
    df = pd.DataFrame(rows)
    # CF_0 = 0: the first flow happens at the end of month 1.
    table = npv_table(params.annual_rate, [0.0, *df["net_flow"]], period="month")[1:]
    df["discount_factor"] = [r["discount_factor"] for r in table]
    df["present_value"] = [r["present_value"] for r in table]
    df["cumulative_pv"] = df["present_value"].cumsum()
    return df


def cost_breakdown(
    scenario: Scenario, params: Params, costs: tuple[CostItem, ...] = DEFAULT_COSTS
) -> pd.DataFrame:
    """Long format: month, cost_type, item, amount (opportunity cost included)."""
    opp_cost = opportunity_cost(params)
    rows = []
    for month in range(1, scenario.horizon_months + 1):
        rows.append(
            {
                "month": month,
                "cost_type": OPPORTUNITY_COST,
                "item": OPPORTUNITY_COST,
                "amount": opp_cost,
            }
        )
        for c in costs:
            amount = c.amount_in(month)
            if amount:
                rows.append(
                    {
                        "month": month,
                        "cost_type": c.cost_type,
                        "item": c.name,
                        "amount": amount,
                    }
                )
    return pd.DataFrame(rows, columns=["month", "cost_type", "item", "amount"])


def npv_of(
    scenario: Scenario, params: Params, costs: tuple[CostItem, ...] = DEFAULT_COSTS
) -> float:
    return float(monthly_flows(scenario, params, costs)["present_value"].sum())


def summarize(
    scenario: Scenario, params: Params, costs: tuple[CostItem, ...] = DEFAULT_COSTS
) -> dict:
    """Headline figures for one scenario."""
    df = monthly_flows(scenario, params, costs)
    pv = df["present_value"]
    dfac = df["discount_factor"]
    npv = float(pv.sum())

    # Discounted payback: the month after which cumulative PV stays >= 0.
    negative = df.loc[df["cumulative_pv"] < 0, "month"]
    if npv < 0:
        payback = None
    elif negative.empty:
        payback = 1
    else:
        payback = int(negative.max()) + 1

    return {
        "scenario": scenario.name,
        "horizon_months": scenario.horizon_months,
        "npv": npv,
        "pv_benefit": float((df["benefit"] * dfac).sum()),
        "pv_opportunity_cost": float((df["opportunity_cost"] * dfac).sum()),
        "pv_direct_costs": float((df["direct_costs"] * dfac).sum()),
        "payback_month": payback,
        # Deepest point of cumulative PV: the funding the project needs before it pays back.
        "max_funding_need": float(max(0.0, -df["cumulative_pv"].min())),
        "final_consultants_staffed": float(df["consultants_staffed"].iloc[-1]),
    }


def _break_even(npv_at_0: float, npv_at_1: float) -> float | None:
    """Root of a function linear in x, given its values at x=0 and x=1."""
    slope = npv_at_1 - npv_at_0
    if slope == 0:
        return None
    return -npv_at_0 / slope


def break_even_margin(
    scenario: Scenario, params: Params, costs: tuple[CostItem, ...] = DEFAULT_COSTS
) -> float | None:
    """Benefit margin at which NPV = 0 (NPV is linear in the margin)."""
    return _break_even(
        npv_of(scenario, replace(params, benefit_margin=0.0), costs),
        npv_of(scenario, replace(params, benefit_margin=1.0), costs),
    )


def break_even_team_size(
    scenario: Scenario, params: Params, costs: tuple[CostItem, ...] = DEFAULT_COSTS
) -> float | None:
    """R&D team size at which NPV = 0 (NPV is linear in the team size)."""
    return _break_even(
        npv_of(scenario, replace(params, n_rd_consultants=0), costs),
        npv_of(scenario, replace(params, n_rd_consultants=1), costs),
    )
